  gallery.appendChild(controls);
  const dotsBox=controls.querySelector('.slider-dots');
  const dots=slides.map((slide,index)=>{
    const dot=document.createElement('button');
    dot.type='button';
    dot.className='slider-dot'+(index===0?' active':'');
    dot.setAttribute('aria-label','Image '+(index+1)+' of '+slides.length);
    dot.addEventListener('click',()=>goTo(index,true));
    dotsBox.appendChild(dot);
    return dot;
  });
  const sync=index=>{
    current=index;
    dots.forEach((dot,i)=>dot.classList.toggle('active',i===current));
  };
  const goTo=(index,userAction=false)=>{
    const next=(index+slides.length)%slides.length;
    track.scrollTo({left:track.clientWidth*next,behavior:'smooth'});
    sync(next);
    if(userAction)restart();
  };
  const restart=()=>{
    clearInterval(timer);
    if(!window.matchMedia('(prefers-reduced-motion: reduce)').matches)timer=setInterval(()=>goTo(current+1),5000);
  };
  controls.querySelector('.prev').addEventListener('click',()=>goTo(current-1,true));
  controls.querySelector('.next').addEventListener('click',()=>goTo(current+1,true));
  let scrollFrame;
  track.addEventListener('scroll',()=>{
    cancelAnimationFrame(scrollFrame);
    scrollFrame=requestAnimationFrame(()=>sync(Math.round(track.scrollLeft/track.clientWidth)));
  },{passive:true});
  gallery.addEventListener('mouseenter',()=>clearInterval(timer));
  gallery.addEventListener('mouseleave',restart);
  gallery.addEventListener('focusin',()=>clearInterval(timer));
  gallery.addEventListener('focusout',restart);
  track.setAttribute('aria-roledescription','carousel');
  track.setAttribute('aria-label','Application gallery '+(galleryIndex+1));
  restart();
